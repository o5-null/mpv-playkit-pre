# Builds the benchmark report: OS / GPU / driver / player + test conditions + result table
# Called by mpv-FilterBench.bat; every parameter arrives through MPV_BENCH_* environment variables.
$ErrorActionPreference = 'SilentlyContinue'

function Env([string]$n) { [Environment]::GetEnvironmentVariable($n) }

$reportPath = Env 'MPV_BENCH_REPORT'
if ([string]::IsNullOrEmpty($reportPath)) { $reportPath = 'installer\report.txt' }
$tsvPath = Env 'MPV_BENCH_TSV'

$lines = New-Object System.Collections.Generic.List[string]

# ---------- header ----------
$lines.Add('mpv frame-interpolation filter benchmark report')
$lines.Add('Generated: ' + (Get-Date).ToString('yyyy-MM-dd HH:mm:ss'))
$lines.Add('')

# ---------- system ----------
$lines.Add('==== System ====')
$os = Get-CimInstance Win32_OperatingSystem
if ($os) {
    $lines.Add('OS          : ' + $os.Caption)
    $lines.Add('Version     : ' + $os.Version + ' (build ' + $os.BuildNumber + ', ' + $os.OSArchitecture + ')')
    if ($os.TotalVisibleMemorySize) {
        $lines.Add(('Memory      : {0:N1} GB' -f ($os.TotalVisibleMemorySize / 1MB)))
    }
}
foreach ($c in @(Get-CimInstance Win32_Processor)) {
    $lines.Add('CPU         : ' + $c.Name.Trim() + ' / ' + $c.NumberOfCores + 'C ' +
        $c.NumberOfLogicalProcessors + 'T / ' + $c.MaxClockSpeed + ' MHz')
}

# ---------- GPU / driver ----------
$lines.Add('')
$lines.Add('==== GPU / driver ====')
foreach ($g in @(Get-CimInstance Win32_VideoController)) {
    $lines.Add('GPU         : ' + $g.Name)
    $lines.Add('  Driver    : ' + $g.DriverVersion + '  (' + $g.DriverDate + ')')
    if ($g.AdapterRAM -gt 0) {
        $lines.Add(('  VRAM      : {0:N1} GB (AdapterRAM is wrong above 4 GB; trust nvidia-smi below)' -f ([double]$g.AdapterRAM / 1GB)))
    }
    if ($g.CurrentHorizontalResolution) {
        $lines.Add('  Display   : ' + $g.CurrentHorizontalResolution + 'x' + $g.CurrentVerticalResolution +
            ' @ ' + $g.CurrentRefreshRate + ' Hz')
    }
}

# nvidia-smi reports VRAM and driver version reliably
$smi = Get-Command nvidia-smi -ErrorAction SilentlyContinue
$smiPath = if ($smi) { $smi.Source } else { $null }
if (-not $smiPath) {
    foreach ($p in @("$env:SystemRoot\System32\nvidia-smi.exe", 'C:\Program Files\NVIDIA Corporation\NVSMI\nvidia-smi.exe')) {
        if (Test-Path -LiteralPath $p) { $smiPath = $p; break }
    }
}
if ($smiPath) {
    foreach ($l in @(& $smiPath --query-gpu=name,driver_version,memory.total --format=csv,noheader)) {
        if ($l) { $lines.Add('nvidia-smi  : ' + $l.Trim()) }
    }
}

# ---------- player ----------
$lines.Add('')
$lines.Add('==== Player ====')
$mpv = Env 'MPV_BENCH_MPV'
if ([string]::IsNullOrEmpty($mpv)) { $mpv = 'mpv.com' }
# PowerShell does not look up bare command names in the current directory
if (-not (Test-Path -LiteralPath $mpv)) {
    $cand = Join-Path (Get-Location).Path $mpv
    if (Test-Path -LiteralPath $cand) { $mpv = $cand }
}
$ver = @(& $mpv --version 2>$null | Select-Object -First 4)
if ($ver.Count -gt 0) { $lines.Add('mpv         : ' + $ver[0].Trim()) }
foreach ($l in $ver) {
    if ($l -match 'FFmpeg version') { $lines.Add('FFmpeg      : ' + $l.Trim()); break }
}

# ---------- test conditions ----------
$lines.Add('')
$lines.Add('==== Test conditions ====')
$clip = Env 'MPV_BENCH_CLIP'
if (Env 'MPV_BENCH_AUTOCLIP') { $clip = $clip + ' (generated by the script)' }
$lines.Add('Clip        : ' + $clip)
$lines.Add('Source      : ' + (Env 'MPV_BENCH_SRCWH'))
$lines.Add('Targets     : ' + (Env 'MPV_BENCH_RES'))
$lines.Add('Multi       : ' + (Env 'MPV_BENCH_MULTI'))
$lines.Add('Verdict     : + = src_fps covers the clip frame rate, - = it does not')
$lines.Add('              a row of dashes = the lane could not run at that multi')
$lines.Add('Playback    : --untimed --frames=600 --d3d11-flip=no --d3d11-sync-interval=0 --autofit=960x540')
$lines.Add('VS-DLSSG    : --vf=d3d11vpp=scale=W/SRCW,vapoursynth=portable_config/vs/MEMC_DLSSG_NV.vpy')
$lines.Add('VS-VFG      : --vf=d3d11vpp=scale=W/SRCW,vapoursynth=portable_config/vs/MEMC_VFG_NV.vpy')
$lines.Add('NATIVE      : --vf=d3d11vpp=scale=W/SRCW,playkit=multi=N:log=no:dll=vs-plugins/vdlssg.dll:proxy_dir=vs-plugins/dlss45')

# ---------- results ----------
$lines.Add('')
$lines.Add('==== Results ==== (out_fps = presented frames per second, src_fps = out_fps / multi)')
$rows = @()
if ($tsvPath -and (Test-Path -LiteralPath $tsvPath)) {
    $rows = @(Get-Content -LiteralPath $tsvPath | Where-Object { $_.Trim() -ne '' })
}
if ($rows.Count -le 1) {
    $lines.Add('(no results: every filter failed to initialize or all lanes were skipped)')
} else {
    # Pad columns so the table can be pasted anywhere
    $table = @()
    foreach ($r in $rows) { $table += ,($r -split "`t") }
    $widths = @()
    for ($i = 0; $i -lt 8; $i++) {
        $w = 0
        foreach ($r in $table) { if ($i -lt $r.Count -and $r[$i].Length -gt $w) { $w = $r[$i].Length } }
        $widths += $w
    }
    foreach ($r in $table) {
        $cells = @()
        for ($i = 0; $i -lt 8; $i++) {
            $v = if ($i -lt $r.Count) { $r[$i] } else { '' }
            $cells += $v.PadRight($widths[$i])
        }
        $lines.Add((($cells -join '  ').TrimEnd()))
    }
}

# ---------- write the file ----------
$text = ($lines -join "`r`n") + "`r`n"
$dir = Split-Path -Parent $reportPath
if ($dir -and -not (Test-Path -LiteralPath $dir)) { New-Item -ItemType Directory -Path $dir -Force | Out-Null }
if ([IO.Path]::IsPathRooted($reportPath)) { $full = $reportPath } else { $full = Join-Path (Get-Location).Path $reportPath }
[IO.File]::WriteAllText($full, $text, (New-Object Text.UTF8Encoding($true)))
'Report written to ' + $full
